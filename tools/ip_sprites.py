"""Brings the rendered character states (tools/ip3d.py sprites OUT) into the app: each PNG trimmed of nothing (the
square frame is the contract — every state shares one camera, so swapping states never jumps), saved as WebP with
alpha in ios/Art/art/ip_<kind>_<state>.webp, and Sprites.swift written with the bead positions and the feet line.

Run: python3 tools/ip_sprites.py OUT
"""
import json, os, sys
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__))
ART = os.path.join(HERE, "..", "ios", "Art", "art")
SWIFT = os.path.join(HERE, "..", "ios", "Mossling", "IP", "Sprites.swift")

def feet(path):
    """The lowest opaque row of the idle state, as a fraction of the square (×100 in the view's units)."""
    im = Image.open(path).getchannel("A"); w, h = im.size; px = im.load()
    for y in range(h - 1, -1, -1):
        if any(px[x, y] > 128 for x in range(0, w, 2)): return 100 * (y + 1) / h
    return 88.0

def main(src):
    meta = json.load(open(os.path.join(src, "sprites.json")))
    n = 0
    for f in sorted(os.listdir(src)):
        if not f.endswith(".png"): continue
        im = Image.open(os.path.join(src, f)).convert("RGBA")
        im.save(os.path.join(ART, "ip_" + f[:-4] + ".webp"), "WEBP", quality=90, method=6)
        n += 1
    beads = {k[5:]: v for k, v in meta.items() if k.startswith("bead_")}
    lines = ["// Generated by tools/ip_sprites.py from the renders of tools/ip3d.py — do not edit by hand.",
             "import CoreGraphics", "", "enum Sprites {",
             f"    static let mossFeet: CGFloat = {feet(os.path.join(src, 'moss_idle.png')):.1f}",
             f"    static let ottoFeet: CGFloat = {feet(os.path.join(src, 'otto_idle.png')):.1f}",
             "    /// The width of each render's square in world units: both are drawn on one scale, so sizes compare truly.",
             f"    static let mossFrame: CGFloat = {meta['frame']['moss'][0]}",
             f"    static let ottoFrame: CGFloat = {meta['frame']['otto'][0]}",
             "    static let bead: [String: CGPoint] = ["]
    lines += [f'        "{k}": CGPoint(x: {v[0]}, y: {v[1]}),' for k, v in sorted(beads.items())]
    lines += ["    ]", "}", ""]
    open(SWIFT, "w").write("\n".join(lines))
    print(n, "sprites;", len(beads), "bead positions")

if __name__ == "__main__":
    main(sys.argv[1])
