#!/usr/bin/env bash
# Mossling (摸索台灯) cloud environment setup:
# Installs Gradle 8.9, Android SDK 35 (platform-tools, platforms;android-35, build-tools;35.0.0),
# Pillow (for tools/ image checks), and configures Java to trust the sandbox proxy CA.
# Note: iOS (SwiftUI / Xcode 26+) cannot be built on Linux; iOS builds/tests run in .github/workflows/ios.yml.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TOOLS="$HOME/.tools"
GRADLE_VER="8.9"
SDK="$HOME/android-sdk"
CMDLINE_ZIP="commandlinetools-linux-11076708_latest.zip"
mkdir -p "$TOOLS" "$SDK"

# 1. Gradle 8.9
if [ ! -x "$TOOLS/gradle-$GRADLE_VER/bin/gradle" ]; then
  curl -fsSL -o /tmp/gradle.zip "https://services.gradle.org/distributions/gradle-$GRADLE_VER-bin.zip"
  python3 -m zipfile -e /tmp/gradle.zip "$TOOLS/"
  chmod +x "$TOOLS/gradle-$GRADLE_VER/bin/gradle"
  rm -f /tmp/gradle.zip
fi

# 2. Android command-line tools
if [ ! -x "$SDK/cmdline-tools/latest/bin/sdkmanager" ]; then
  curl -fsSL -o /tmp/cmdline.zip "https://dl.google.com/android/repository/$CMDLINE_ZIP"
  rm -rf /tmp/cmdline && mkdir -p /tmp/cmdline
  python3 -m zipfile -e /tmp/cmdline.zip /tmp/cmdline
  mkdir -p "$SDK/cmdline-tools"
  rm -rf "$SDK/cmdline-tools/latest"
  mv /tmp/cmdline/cmdline-tools "$SDK/cmdline-tools/latest"
  chmod +x "$SDK/cmdline-tools/latest/bin/"*
  rm -rf /tmp/cmdline /tmp/cmdline.zip
fi

# 3. Java truststore + proxy helper (sdkmanager & Gradle ignore HTTPS_PROXY and system PEM bundle)
JAVA_HOME_DIR="$(dirname "$(dirname "$(readlink -f "$(command -v java)")")")"
TRUST="$TOOLS/cacerts"
if [ ! -s "$TRUST" ]; then
  rm -f "$TRUST"
  if [ -f "$JAVA_HOME_DIR/lib/security/cacerts" ]; then
    cp -L "$JAVA_HOME_DIR/lib/security/cacerts" "$TRUST"
    chmod u+w "$TRUST"
  elif [ -f /etc/ssl/certs/ca-certificates.crt ]; then
    rm -rf /tmp/cabundle && mkdir -p /tmp/cabundle
    awk '/BEGIN CERTIFICATE/{n++} n{print > ("/tmp/cabundle/c" n ".pem")}' /etc/ssl/certs/ca-certificates.crt
    for f in /tmp/cabundle/*.pem; do
      keytool -importcert -noprompt -keystore "$TRUST" -storetype PKCS12 -storepass changeit \
        -alias "sys-$(basename "$f" .pem)" -file "$f" >/dev/null 2>&1 || true
    done
    rm -rf /tmp/cabundle
  fi
fi
for crt in /usr/local/share/ca-certificates/*.crt; do
  [ -f "$crt" ] || continue
  alias="local-$(basename "$crt" .crt)"
  keytool -list -keystore "$TRUST" -storepass changeit -alias "$alias" >/dev/null 2>&1 || \
    keytool -importcert -noprompt -keystore "$TRUST" -storepass changeit -alias "$alias" -file "$crt" >/dev/null
done

cat > "$TOOLS/java-env.sh" <<EOF
# Generated by .agents/setup.sh: route Java (Gradle, sdkmanager) through the local proxy and trust its CA.
JOPTS="-Djavax.net.ssl.trustStore=$TRUST -Djavax.net.ssl.trustStorePassword=changeit"
_p="\${HTTPS_PROXY:-\${https_proxy:-}}"
if [ -n "\$_p" ]; then
  _hp="\${_p#*://}"; _hp="\${_hp%/}"; _hp="\${_hp##*@}"
  JOPTS="\$JOPTS -Dhttps.proxyHost=\${_hp%:*} -Dhttps.proxyPort=\${_hp##*:} -Dhttp.proxyHost=\${_hp%:*} -Dhttp.proxyPort=\${_hp##*:} -Dhttp.nonProxyHosts=localhost|127.0.0.1"
fi
export JAVA_TOOL_OPTIONS="\$JOPTS"
unset _p _hp JOPTS
EOF
# shellcheck disable=SC1091
. "$TOOLS/java-env.sh"

# 4. Android SDK 35 components
export ANDROID_HOME="$SDK" ANDROID_SDK_ROOT="$SDK"
if [ ! -d "$SDK/platforms/android-35" ] || [ ! -d "$SDK/build-tools/35.0.0" ]; then
  yes | "$SDK/cmdline-tools/latest/bin/sdkmanager" --licenses >/dev/null || true
  "$SDK/cmdline-tools/latest/bin/sdkmanager" "platform-tools" "platforms;android-35" "build-tools;35.0.0" >/dev/null
fi

# 5. Python Pillow for tools/ scripts
python3 -c "import PIL" 2>/dev/null || python3 -m pip install --user --quiet --break-system-packages pillow

# 6. Persist PATH and env vars in ~/.bashrc for non-interactive shells
touch "$HOME/.bashrc"
sed -i '/case \$- in/,/esac/d' "$HOME/.bashrc" 2>/dev/null || true
for line in \
  "export ANDROID_HOME=$SDK" \
  "export ANDROID_SDK_ROOT=$SDK" \
  "export PATH=$TOOLS/gradle-$GRADLE_VER/bin:$SDK/cmdline-tools/latest/bin:$SDK/platform-tools:\$PATH" \
  "[ -f $TOOLS/java-env.sh ] && . $TOOLS/java-env.sh"; do
  grep -qxF "$line" "$HOME/.bashrc" || echo "$line" >> "$HOME/.bashrc"
done

# 7. Write local.properties (gitignored)
echo "sdk.dir=$SDK" > "$REPO_ROOT/local.properties"
echo "Mossling environment ready."
